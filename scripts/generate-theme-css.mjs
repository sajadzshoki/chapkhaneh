/**
 * Generates the build-time CSS from `shared/theme/brand.ts`.
 *
 * Why this exists
 * ---------------
 * The palette has to appear in three forms, and two of them must be *literal
 * CSS text* rather than values computed at runtime:
 *
 *   1. `shared/theme/brand.ts`      — the source of truth (TypeScript)
 *   2. `app/assets/css/main.css`    — `@theme static` block. Tailwind v4 reads
 *                                     this at build time to emit utility
 *                                     classes; it cannot import a .ts file.
 *   3. `app/assets/css/tokens.css`  — first-paint defaults, and the fallback
 *                                     if the database is unreachable.
 *
 * Rather than maintaining those by hand and letting them drift, this script
 * derives 2 and 3 from 1. The output is committed, so a normal build needs no
 * extra step and there is no runtime code generation.
 *
 * Run after changing `brand.ts`:
 *
 *     npm run theme:generate
 *
 * Note this only sets the *defaults*. The live palette comes from PostgreSQL
 * via `/theme.css`, which overrides these at runtime with no rebuild.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')

/**
 * Reads the colour literals straight out of brand.ts.
 *
 * A regex rather than importing the module: this runs as plain node with no
 * TypeScript loader, and the file is a flat set of literals by design.
 */
function parseBrand() {
  const source = readFileSync(resolve(root, 'shared/theme/brand.ts'), 'utf8')

  const scale = (name) => {
    const block = source.match(new RegExp(`const ${name}Scale: ColorScale = \\{([^}]+)\\}`))
    if (!block) throw new Error(`Could not find ${name}Scale in brand.ts`)
    return Object.fromEntries(
      [...block[1].matchAll(/(\d+):\s*'(#[0-9a-fA-F]{6})'/g)].map(m => [m[1], m[2]]),
    )
  }

  const colorsBlock = source.match(/colors: \{([\s\S]*?)\} satisfies SemanticTokens/)
  if (!colorsBlock) throw new Error('Could not find the semantic colors block in brand.ts')

  const semantic = Object.fromEntries(
    [...colorsBlock[1].matchAll(/'?([a-z-]+)'?:\s*(?:'(#[0-9a-fA-F]{6})'|([a-zA-Z]+Scale)\[(\d+)\])/g)]
      .map((m) => {
        if (m[2]) return [m[1], m[2]]
        const scaleName = m[3].replace('Scale', '')
        return [m[1], scale(scaleName)[m[4]]]
      }),
  )

  const radius = Object.fromEntries(
    [...(source.match(/radius: \{([^}]+)\}/)?.[1] ?? '')
      .matchAll(/(\w+):\s*'([^']+)'/g)].map(m => [m[1], m[2]]),
  )

  const fonts = Object.fromEntries(
    [...(source.match(/fonts: \{([\s\S]*?)\},/)?.[1] ?? '')
      .matchAll(/(\w+):\s*'([^']+)'/g)].map(m => [m[1], m[2]]),
  )

  return {
    scales: { primary: scale('primary'), secondary: scale('secondary'), accent: scale('accent') },
    semantic,
    radius,
    fonts,
  }
}

const brand = parseBrand()
const GENERATED = '/* GENERATED by scripts/generate-theme-css.mjs — edit shared/theme/brand.ts instead. */'

/* ----------------------------- tokens.css -------------------------------- */

const order = [
  ['primary', 'primary-hover', 'primary-contrast', 'secondary', 'secondary-hover', 'accent', 'accent-hover'],
  ['background', 'surface', 'surface-muted'],
  ['foreground', 'foreground-soft', 'muted'],
  ['border', 'border-strong'],
  ['success', 'warning', 'danger'],
]

const tokens = `/* ---------------------------------------------------------------------------
   Semantic design tokens — DEFAULTS ONLY.

   ${GENERATED}

   These guarantee a correct first paint and act as the fallback when the
   database is unreachable. The live palette is served by \`/theme.css\` from
   the \`theme_settings\` table and overrides everything here, which is why a
   theme change needs no rebuild.
   --------------------------------------------------------------------------- */
:root {
${order.map(group =>
  group.map(key => `  --color-${key}: ${brand.semantic[key]};`).join('\n'),
).join('\n\n')}

${Object.entries(brand.radius).map(([k, v]) => `  --radius-${k}: ${v};`).join('\n')}

${Object.entries(brand.fonts).map(([k, v]) => `  --font-${k}: ${v};`).join('\n')}

  --shadow-sm: 0 1px 2px rgba(20, 24, 29, 0.06);
  --shadow-md: 0 4px 16px rgba(20, 24, 29, 0.08);

  --container-max: 1280px;
  --header-height: 76px;
}
`

writeFileSync(resolve(root, 'app/assets/css/tokens.css'), tokens)

/* ------------------------- main.css @theme block -------------------------- */

const themeBlock = [
  '@theme static {',
  '  /* ' + GENERATED.replace('/* ', '').replace(' */', '') + ' */',
  ...Object.entries(brand.scales).flatMap(([name, steps]) => [
    '',
    ...Object.entries(steps).map(([step, value]) => `  --color-${name}-${step}: ${value};`),
  ]),
  '}',
].join('\n')

const mainPath = resolve(root, 'app/assets/css/main.css')
const main = readFileSync(mainPath, 'utf8')
const replaced = main.replace(/@theme static \{[\s\S]*?\n\}/, themeBlock)

if (replaced === main && !main.includes(themeBlock)) {
  throw new Error('Could not locate the @theme static block in main.css')
}

writeFileSync(mainPath, replaced)

console.log('[theme] regenerated app/assets/css/tokens.css and the @theme block in main.css')
